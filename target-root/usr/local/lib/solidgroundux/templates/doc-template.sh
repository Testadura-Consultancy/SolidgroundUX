# Documentation syntax quick reference:
#
#   Section indicators:
#     # - Heading              Level 1 / top-level section
#     # -- Section             Level 2 section
#     # --- Subsection         Level 3 subsection
#
#   Documentation item/header indicators:
#     # fn:                    Function or method
#     # var:                   Variable
#     # cls:                   Class
#     # doc:                   General documentation
#     # fn$ / var$ / cls$ / doc$
#                              Template documentation variants
#
#   Documentation and style hints:
#     # > text                 Plain documentation / normal style
#     # : text                 label
#     # . text                 highlight
#     # ! text                 emphasis
#     # _ text                 underline
#     # ~ text                 quote / aside
#     # - text                 list item
#                              indent is reserved; leading whitespace prevents marker parsing
#
#   Images:
#     # . Images               Begin an image group (Image is also accepted; : may replace .)
#     # filename.png :: Caption
#     #                        Blank documentation line ends the image block
#
#   Tables:
#     # . Table                Begin a table
#     # ! Header 1 :: Header 2 First row is the semantic header; any style hint may be used
#     # Value 1 :: Value 2     Following rows; any implemented style hint may be used
#     # . EndTable             Explicitly end the table
#                              A blank documentation line also ends a table for compatibility
